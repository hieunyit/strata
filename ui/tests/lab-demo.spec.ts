import { test, expect } from '@playwright/test';
import { spawn, ChildProcess } from 'child_process';
import path from 'path';
import fs from 'fs';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ARTIFACT_DIR = '/home/hellc/.gemini/antigravity/brain/ddc01b2c-60fa-4e49-be0a-74ddc4325ede';
const LOCAL_ARTIFACT_DIR = path.resolve(__dirname, 'artifacts');

test.describe('Strata WAF - Live Lab Integration Demo', () => {
  let cpProcess: ChildProcess;
  let nginxProcess: ChildProcess;
  let realBlockId: string = '';

  test.beforeAll(async () => {
    // Ensure artifact dirs exist
    if (!fs.existsSync(ARTIFACT_DIR)) {
      fs.mkdirSync(ARTIFACT_DIR, { recursive: true });
    }
    if (!fs.existsSync(LOCAL_ARTIFACT_DIR)) {
      fs.mkdirSync(LOCAL_ARTIFACT_DIR, { recursive: true });
    }

    // 1. Start Control Plane server on :8080
    cpProcess = spawn('/tmp/strata-cp', ['--addr', ':8080', '--seed=false'], {
      stdio: 'inherit',
    });

    // Wait for control plane to be ready
    await new Promise((resolve) => setTimeout(resolve, 2000));

    // 2. Start NGINX on :8090
    const nginxConf = `
daemon off;
error_log /tmp/strata-nginx-lab/logs/error.log info;
pid /tmp/strata-nginx-lab/nginx.pid;
worker_processes 1;
load_module /home/hellc/strata/build/nginx-1.30.5/objs/ngx_http_strata_module.so;

events {
    worker_connections 1024;
}

http {
    access_log /tmp/strata-nginx-lab/logs/access.log;
    client_body_temp_path /tmp/strata-nginx-lab/client_body;
    proxy_temp_path /tmp/strata-nginx-lab/proxy_temp;
    fastcgi_temp_path /tmp/strata-nginx-lab/fastcgi_temp;
    uwsgi_temp_path /tmp/strata-nginx-lab/uwsgi_temp;
    scgi_temp_path /tmp/strata-nginx-lab/scgi_temp;

    strata_control_file  /home/hellc/strata/connectors/nginx/t/fixtures/bundle/control;
    strata_bundle_dir    /home/hellc/strata/connectors/nginx/t/fixtures/bundle;
    strata_bundle_pubkey /home/hellc/strata/connectors/nginx/t/fixtures/bundle.pub;
    strata_node_id       web-01;

    server {
        listen 8090;

        location /backend/ {
            strata off;
            return 200 "backend ok\\n";
        }

        location /t {
            strata on;
            strata_policy example-api;
            proxy_pass http://127.0.0.1:8090/backend/;
        }
    }
}
`;
    fs.mkdirSync('/tmp/strata-nginx-lab/logs', { recursive: true });
    fs.writeFileSync('/tmp/strata-nginx-lab/nginx.conf', nginxConf);

    nginxProcess = spawn('/home/hellc/strata/build/nginx-1.30.5/objs/nginx', ['-c', '/tmp/strata-nginx-lab/nginx.conf'], {
      stdio: 'pipe',
    });

    await new Promise((resolve) => setTimeout(resolve, 1500));

    // 3. Send attack request to NGINX lab
    const res = await fetch('http://127.0.0.1:8090/t?q=STRATA-TEST-BLOCK', {
      headers: {
        'Accept': 'application/json',
      },
    });

    expect(res.status).toBe(403);
    const blockIdHeader = res.headers.get('x-strata-block-id');
    const body = await res.json();

    realBlockId = blockIdHeader || body.block_id;
    console.log(`[LAB TEST] Real Block ID generated by NGINX: ${realBlockId}`);
    expect(realBlockId).toMatch(/^STR-[0-9A-HJ-NP-Z]{4}-[0-9A-HJ-NP-Z]{4}-[0-9A-HJ-NP-Z]{4}-[0-9A-HJ-NP-Z]{4}$/);

    // 4. Ingest event to Control Plane
    const eventPayload = {
      block_id: realBlockId,
      timestamp: new Date().toISOString(),
      node_id: 'web-01',
      connector_type: 'nginx',
      policy_id: 'example-api',
      policy_version: 1,
      client_ip: '127.0.0.1',
      identity: 'lab-tester',
      request_id: 'req-lab-e2e-block',
      http_method: 'GET',
      http_host: '127.0.0.1:8090',
      http_path: '/t?q=STRATA-TEST-BLOCK',
      status_code: 403,
      action: 'block',
      score_protocol: 25,
      score_sqli: 0,
      score_xss: 0,
      score_anomaly: 25,
      matched_rules: [100001],
      violations: [
        {
          rule_id: 100001,
          layer: 'protocol',
          field: 'uri.query.q',
          snippet: 'STRATA-TEST-BLOCK',
        },
      ],
      received_at: new Date().toISOString(),
    };

    const ingestRes = await fetch('http://127.0.0.1:8080/v1/events:ingest', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify([eventPayload]),
    });
    expect(ingestRes.status).toBe(200);
  });

  test.afterAll(async () => {
    if (nginxProcess) {
      nginxProcess.kill('SIGTERM');
    }
    if (cpProcess) {
      cpProcess.kill('SIGTERM');
    }
  });

  test('lookup real NGINX Block ID on UI and capture screenshot', async ({ page }) => {
    expect(realBlockId).toBeTruthy();

    // 1. Open Web UI
    await page.goto('/');

    // 2. Type the real Block ID into Header search bar
    const searchInput = page.getByTestId('block-id-search-input');
    await searchInput.fill(realBlockId);

    const searchBtn = page.getByTestId('block-id-search-btn');
    await searchBtn.click();

    // 3. Verify Decision Trace modal is displayed with real event data
    const modal = page.getByTestId('decision-trace-modal');
    await expect(modal).toBeVisible();

    await expect(modal.getByText(realBlockId)).toBeVisible();
    await expect(modal.getByText('web-01')).toBeVisible();
    await expect(modal.getByText('example-api (v1)')).toBeVisible();
    await expect(modal.getByText('Rule 100001')).toBeVisible();
    await expect(modal.getByTestId('violation-snippet')).toHaveText('STRATA-TEST-BLOCK');

    // 4. Capture screenshot
    const screenshotPath = path.join(ARTIFACT_DIR, 'decision_trace_lab.png');
    const localScreenshotPath = path.join(LOCAL_ARTIFACT_DIR, 'decision_trace_lab.png');

    await page.screenshot({ path: screenshotPath, fullPage: true });
    await page.screenshot({ path: localScreenshotPath, fullPage: true });

    console.log(`[LAB TEST] Screenshot saved to ${screenshotPath} and ${localScreenshotPath}`);
  });
});
