#!/usr/bin/env python3
"""Generates engine/src/detectors/injection/sqli_data.rs from libinjection's
src/libinjection_sqli_data.h (keywords, operators and fingerprints, sorted
as the C binary search expects).

Usage: gen-sqli-data.py <libinjection_sqli_data.h> > sqli_data.rs
"""
import re
import sys

src = open(sys.argv[1], encoding="latin-1").read()
body = src[src.index("static const keyword_t sql_keywords[] = {"):]
body = body[: body.index("};")]
entries = re.findall(r'\{"((?:[^"\\]|\\.)*)", \'(.)\'\}', body)
size = int(re.search(r"sql_keywords_sz = (\d+);", src).group(1))
assert len(entries) == size, (len(entries), size)


def rust_bytes(word):
    out = []
    for ch in word.encode("latin-1").decode("unicode_escape").encode("latin-1"):
        c = chr(ch)
        if c in '"\\':
            out.append("\\" + c)
        elif 32 <= ch < 127:
            out.append(c)
        else:
            out.append("\\x%02x" % ch)
    return 'b"' + "".join(out) + '"'


print("// @generated by engine/tools/libinjection/gen-sqli-data.py from")
print("// libinjection v3.10.0 src/libinjection_sqli_data.h (BSD-3-Clause,")
print("// Copyright (c) 2012-2016 Nick Galbreath; see engine/NOTICE).")
print("// Do not edit by hand.")
print()
print("/// (upper-case word, token type), sorted for `bsearch_keyword_type`;")
print("/// type b'F' entries are the SQLi fingerprints ('0' + fingerprint).")
print("pub static KEYWORDS: &[(&[u8], u8)] = &[")
for word, typ in entries:
    print("    (%s, b'%s')," % (rust_bytes(word), typ if typ != "'" else "\\'"))
print("];")
