#!/usr/bin/env python3
"""Generates engine/src/transform/tables.rs from pinned upstream sources:

- golang.org/x/net/html (BSD-3-Clause) entity.go + escape.go, the tables
  behind html.UnescapeString, which Coraza's htmlEntityDecode uses;
- Coraza (Apache-2.0) unicode_bestfit.go, the %uXXXX best-fit table of
  urlDecodeUni (from ModSecurity's unicode.mapping, codepage 20127).

Usage: gen-transform-tables.py <entity.go> <escape.go> <unicode_bestfit.go>
"""
import re
import sys

GO_NET = "golang/net c1d31df183e51b1075a2fd670d6f6f4efb871773 (v0.61.0)"
CORAZA = "corazawaf/coraza 9f8521398d1ff023b958fad0b944cac265763866 (v3.8.1)"

entity_go, escape_go, bestfit_go = (open(p, encoding="utf-8").read() for p in sys.argv[1:4])

one = re.findall(r'^\s*"([A-Za-z0-9]+;?)":\s*\'\\U([0-9A-Fa-f]{8})\',', entity_go, re.M)
two = re.findall(r'^\s*"([A-Za-z0-9]+;?)":\s*\{\'\\u([0-9A-Fa-f]{4})\',\s*\'\\u([0-9A-Fa-f]{4})\'\}', entity_go, re.M)
longest = int(re.search(r"longestEntityWithoutSemicolon\s*=\s*(\d+)", entity_go).group(1))
table = re.search(r"replacementTable = \[\.\.\.\]rune\{(.*?)\n\}", escape_go, re.S).group(1)
repl = re.findall(r"^\s*'\\u([0-9A-Fa-f]{4})',", table, re.M)
best = re.findall(r"^\s*0x([0-9a-f]+):\s*0x([0-9a-f]+),", bestfit_go, re.M)

assert len(one) > 2000 and len(two) > 50 and len(repl) == 32 and len(best) > 300, (len(one), len(two), len(repl), len(best))

out = []
w = out.append
w("// GENERATED by engine/tools/gen-transform-tables.py; do not edit.")
w("//")
w(f"// HTML entities and the Windows-1252 table: {GO_NET},")
w("// Copyright 2009 The Go Authors, BSD-3-Clause (see engine/NOTICE).")
w(f"// Unicode best-fit table: {CORAZA},")
w("// Copyright the OWASP Coraza contributors, Apache-2.0 (see engine/NOTICE).")
w("")
w(f"pub const LONGEST_ENTITY_WITHOUT_SEMICOLON: usize = {longest};")
w("")
w("/// Named references with one code point, sorted by name.")
w("pub static ENTITY: &[(&str, u32)] = &[")
for name, cp in sorted(one):
    w(f'    ("{name}", 0x{int(cp, 16):X}),')
w("];")
w("")
w("/// Named references with two code points, sorted by name.")
w("pub static ENTITY2: &[(&str, u32, u32)] = &[")
for name, a, b in sorted(two):
    w(f'    ("{name}", 0x{int(a, 16):X}, 0x{int(b, 16):X}),')
w("];")
w("")
w("/// Numeric references 0x80..=0x9F, read as Windows-1252.")
w("pub static REPLACEMENT: [u32; 32] = [")
w("    " + ", ".join(f"0x{int(c, 16):X}" for c in repl) + ",")
w("];")
w("")
w("/// %uXXXX best-fit code point -> ASCII byte, sorted by code point.")
w("pub static BEST_FIT: &[(u32, u8)] = &[")
for cp, b in sorted(best, key=lambda x: int(x[0], 16)):
    w(f"    (0x{int(cp, 16):04X}, 0x{int(b, 16):02X}),")
w("];")
open("engine/src/transform/tables.rs", "w").write("\n".join(out) + "\n")
print(f"{len(one)} entities, {len(two)} double entities, {len(best)} best-fit entries")
