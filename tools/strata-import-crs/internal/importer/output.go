package importer

import (
	"bytes"
	"fmt"
	"io"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Marshal writes a group as an IR document (YAML), rules in id order and
// keys in the IR's order.
func Marshal(im *Imported, version string) ([]byte, error) {
	order := []string{"id", "name", "layer", "stage", "match", "score", "severity", "paranoia_level", "metadata"}
	rules := &yaml.Node{Kind: yaml.SequenceNode}
	sorted := append([]map[string]any(nil), im.Rules...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i]["id"].(int) < sorted[j]["id"].(int) })
	for _, r := range sorted {
		m := &yaml.Node{Kind: yaml.MappingNode}
		for _, k := range order {
			v, ok := r[k]
			if !ok {
				continue
			}
			var vn yaml.Node
			if err := vn.Encode(v); err != nil {
				return nil, err
			}
			m.Content = append(m.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, &vn)
		}
		rules.Content = append(rules.Content, m)
	}
	var ir, rs yaml.Node
	if err := ir.Encode(1); err != nil {
		return nil, err
	}
	if err := rs.Encode(map[string]any{"name": im.Group.Ruleset, "version": version}); err != nil {
		return nil, err
	}
	root := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{
		{Kind: yaml.ScalarNode, Value: "ir_version"}, &ir,
		{Kind: yaml.ScalarNode, Value: "ruleset"}, &rs,
		{Kind: yaml.ScalarNode, Value: "rules"}, rules,
	}}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# OWASP CRS %s, %s: generated by tools/strata-import-crs, do not edit.\n", version, im.Group.File)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(root); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// Report writes the import report: rate per group, rules left out with
// the reason, and changes made to imported rules.
func (r *Result) Report(w io.Writer, version string) {
	fmt.Fprintf(w, "# CRS %s import report\n\nGenerated by `strata-import-crs import` (W05-S-01, W06-S-01): rules the IR can express are in `rules/crs/`; the others are listed with the reason. Paranoia level 1 only.\n\n", version)
	fmt.Fprintf(w, "| Group | Rules | Imported | Rate |\n| --- | ---: | ---: | ---: |\n")
	read, imp := 0, 0
	for _, g := range r.Groups {
		read += g.Read
		imp += len(g.Rules)
		fmt.Fprintf(w, "| %s | %d | %d | %.0f%% |\n", strings.TrimSuffix(g.Group.File, ".conf"), g.Read, len(g.Rules), 100*float64(len(g.Rules))/float64(max(g.Read, 1)))
	}
	fmt.Fprintf(w, "| **all** | %d | %d | %.0f%% |\n", read, imp, 100*float64(imp)/float64(max(read, 1)))
	plumbing := 0
	for _, s := range r.Skipped {
		if strings.HasPrefix(s.Reason, "paranoia level") || strings.HasPrefix(s.Reason, "does not block") || strings.HasPrefix(s.Reason, "SecAction") {
			plumbing++
		}
	}
	det := read - plumbing
	fmt.Fprintf(w, "\nOf the %d rules, %d are CRS plumbing (paranoia level checks, initialization: no detection) or above paranoia level 1. "+
		"Of the other %d, the paranoia level 1 detection rules, **%d are imported (%.0f%%)**.\n", read, plumbing, det, imp, 100*float64(imp)/float64(max(det, 1)))
	counts := map[string]int{}
	for _, s := range r.Skipped {
		reason := s.Reason
		for _, p := range []string{"paranoia level", "transformation", "operator", "variable", "compiler", "pattern selector", "macro"} {
			if strings.HasPrefix(reason, p) {
				reason = p + strings.SplitN(strings.TrimPrefix(reason, p), " (", 2)[0]
				break
			}
		}
		counts[reason]++
	}
	keys := make([]string, 0, len(counts))
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		return counts[keys[i]] > counts[keys[j]] || counts[keys[i]] == counts[keys[j]] && keys[i] < keys[j]
	})
	fmt.Fprintf(w, "\n## Why rules were left out\n\n| Reason | Rules |\n| --- | ---: |\n")
	for _, k := range keys {
		fmt.Fprintf(w, "| %s | %d |\n", k, counts[k])
	}
	fmt.Fprintf(w, "\n## Rules left out\n\n| Group | Rule | Reason |\n| --- | --- | --- |\n")
	for _, s := range r.Sorted() {
		fmt.Fprintf(w, "| %s | %d | %s |\n", strings.TrimSuffix(s.Group, ".conf"), s.Rule, strings.ReplaceAll(s.Reason, "|", "\\|"))
	}
	fmt.Fprintf(w, "\n## Changes to imported rules\n\n| Rule | Change |\n| --- | --- |\n")
	for _, g := range r.Groups {
		for _, n := range g.Notes {
			fmt.Fprintf(w, "| %d | %s |\n", n.Rule, strings.ReplaceAll(n.Text, "|", "\\|"))
		}
	}
}
